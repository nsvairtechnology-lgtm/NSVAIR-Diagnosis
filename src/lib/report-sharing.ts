/**
 * Dispatch message directly to WhatsApp Web / App
 */
export function openWhatsApp(phone: string, message: string) {
  const targetPhone = cleanPhoneNumber(phone)
  const encoded = encodeURIComponent(message)
  const url = `https://wa.me/${targetPhone}?text=${encoded}`
  window.open(url, '_blank')
}

/**
 * Dispatch email via Gmail Web or Default Email Client (mailto:)
 */
export function openEmail(
  email: string,
  subject: string,
  body: string,
  preferGmailWeb: boolean = true
) {
  const targetEmail = email.trim() || DEFAULT_GMAIL_ADDRESS
  const encSubject = encodeURIComponent(subject)
  const encBody = encodeURIComponent(body)

  if (preferGmailWeb) {
    // Open Gmail compose window directly in browser
    const gmailUrl = `https://mail.google.com/mail/?view=cm&fs=1&to=${encodeURIComponent(targetEmail)}&su=${encSubject}&body=${encBody}`
    window.open(gmailUrl, '_blank')
  } else {
    // Fallback to mailto client
    window.location.href = `mailto:${targetEmail}?subject=${encSubject}&body=${encBody}`
  }
}
